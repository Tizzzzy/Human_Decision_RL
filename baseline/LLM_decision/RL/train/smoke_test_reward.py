def test_policy_model_loading():
    """
    Test 5 (Optional): Try loading policy model via AutoModelForCausalLM.

    This is the "flagged risk" from the plan: confirming that Qwen3.6-27B
    can load via AutoModelForCausalLM and generate completions.
    """
    print("\n" + "="*70)
    print("TEST 5 (Optional): Policy Model Loading & Generation")
    print("="*70)

    try:
        print("[Test] Loading Qwen3.6-27B tokenizer...")
        policy_tokenizer = AutoTokenizer.from_pretrained(
            config.POLICY_MODEL_NAME,
            cache_dir=config.POLICY_CACHE_DIR,
            trust_remote_code=True,
        )
        print("[✓] Tokenizer loaded")

        print("[Test] Loading Qwen3.6-27B via AutoModelForCausalLM...")
        from transformers import AutoModelForCausalLM

        # Try loading with smaller version first to avoid immediate memory issues on login node
        # (just test that the loading succeeds, not full inference)
        policy_model = AutoModelForCausalLM.from_pretrained(
            config.POLICY_MODEL_NAME,
            torch_dtype=torch.bfloat16,
            device_map="auto",
            cache_dir=config.POLICY_CACHE_DIR,
            trust_remote_code=True,
        )
        print("[✓] Model loaded via AutoModelForCausalLM")

        # Quick generate test on a tiny sample
        print("[Test] Attempting a small generation...")
        test_text = "Hello world"
        from . import prompt_templates as pt
        prompt = pt.build_policy_prompt(test_text, policy_tokenizer)

        # Encode
        inputs = policy_tokenizer(
            prompt,
            return_tensors="pt",
            truncation=True,
            max_length=512,
        ).to(policy_model.device)

        # Generate a few tokens (lightweight test)
        with torch.no_grad():
            output_ids = policy_model.generate(
                **inputs,
                max_new_tokens=10,
                temperature=1.0,
                top_p=1.0,
                do_sample=True,
            )

        # Decode
        generated_text = policy_tokenizer.decode(
            output_ids[0][inputs["input_ids"].shape[1]:],
            skip_special_tokens=True,
        )

        print(f"[Test] Generated text: {generated_text[:100]}")
        print("[✓] Model generation works")

        print("[✓] Policy model loading test PASSED")

    except Exception as e:
        print(f"[✗] Policy model loading test FAILED: {e}")
        print("[!] This is the flagged risk from the plan. If AutoModelForCausalLM fails:")
        print("    - Try loading via AutoModelForMultimodalLM instead (less ideal)")
        print("    - Or check if Qwen3.6-27B supports causal-LM inference")
        return False

    return True


