def test_representation_shape():
    """
    Test 1: Extract representation and check shape.
    """
    print("\n" + "="*70)
    print("TEST 1: Representation Extraction Shape")
    print("="*70)

    # Simple test prompt
    test_prompt = "This is a test text for representation extraction."

    print(f"[Test] Extracting representation for prompt: {test_prompt[:50]}...")
    rep = reward.extract_representation(test_prompt)

    print(f"[Test] Representation shape: {rep.shape}")
    print(f"[Test] Representation dtype: {rep.dtype}")
    print(f"[Test] Representation device: {rep.device}")

    assert rep.shape == torch.Size([5120]), f"Expected shape [5120], got {rep.shape}"
    assert rep.dtype == torch.float32, f"Expected dtype float32, got {rep.dtype}"

    print("[✓] Representation shape test PASSED")


def test_probe_output_range():
    """
    Test 2: Probe ensemble P(AI) output is in valid [0,1] range.
    """
    print("\n" + "="*70)
    print("TEST 2: Probe Ensemble Output Range")
    print("="*70)

    # Create a dummy representation
    dummy_rep = torch.randn(5120, dtype=torch.float32)

    print("[Test] Computing P(AI) for dummy representation using ensemble...")
    p_ai = reward.probe_p_ai(dummy_rep)

    print(f"[Test] Ensemble P(AI) = {p_ai:.4f}")

    assert 0.0 <= p_ai <= 1.0, f"P(AI) out of range [0,1]: {p_ai}"
    assert isinstance(p_ai, float), f"Expected float, got {type(p_ai)}"

    print("[✓] Probe ensemble output range test PASSED")


def test_reward_formula():
    """
    Test 3: Reward formula behavior on hand-picked values.
    """
    print("\n" + "="*70)
    print("TEST 3: Reward Formula Behavior")
    print("="*70)

    test_cases = [
        # (p_ai, y, expected_description)
        (0.99, 1.0, "high reward (confident & correct for AI text)"),
        (0.01, 0.0, "high reward (confident & correct for Human text)"),
        (0.99, 0.0, "large negative reward (confident & wrong for Human text)"),
        (0.01, 1.0, "large negative reward (confident & wrong for AI text)"),
        (0.50, 0.5, "medium reward (uncertain)"),
    ]

    for p_ai, y, description in test_cases:
        reward_val = reward.compute_reward(p_ai, y)
        print(f"[Test] p_ai={p_ai:.2f}, y={y:.1f}: reward={reward_val:.4f} ({description})")

        # Sanity checks
        if p_ai == y or (p_ai > 0.9 and y == 1.0) or (p_ai < 0.1 and y == 0.0):
            # Confident & correct: should be closer to 1.0
            assert reward_val > -1.0, f"Expected reward > -1 for confident-correct case, got {reward_val}"
        elif (p_ai > 0.9 and y == 0.0) or (p_ai < 0.1 and y == 1.0):
            # Confident & wrong: should be strongly negative
            assert reward_val < 0.0, f"Expected reward < 0 for confident-wrong case, got {reward_val}"

    print("[✓] Reward formula test PASSED")


